import { readFileSync } from 'node:fs';
const fields = JSON.parse(
  readFileSync(new URL('./tool-schema-fields.json', import.meta.url), 'utf8'),
);
const snake = (key) =>
  key
    .replace(/^\$/, '')
    .replace(/[A-Z]/g, (letter) => '_' + letter.toLowerCase());
const pascal = (key) =>
  key.replace(/^\$/, '').replace(/^./, (letter) => letter.toUpperCase());
// Refuse vocabulary drift between model dispatch and generated SDK contracts.
const java = readFileSync(
  new URL(
    '../plowshare-protocol/src/main/java/io/aeyer/plowshare/protocol/SchemaDefinition.java',
    import.meta.url,
  ),
  'utf8',
);
const record = java.slice(
  java.indexOf('public record SchemaDefinition('),
  java.indexOf(') {', java.indexOf('public record SchemaDefinition(')),
);
const declared = [
  ...record.matchAll(
    /(?:@JsonProperty\("([^"\n]+)"\)\s*)?(?:Types|String|Map<String, SchemaDefinition>|List<[^>]+>|Rule|SchemaDefinition|Literal|BigDecimal|Integer|Boolean)\s+(\w+)/g,
  ),
].map((match) => match[1] ?? match[2]);
if (JSON.stringify(declared) !== JSON.stringify(Object.keys(fields)))
  throw new Error('Shared schema vocabulary differs from generator');
export function toolSchemaContracts() {
  const head = 'Generated by scripts/generate-sdk-contracts.mjs; do not edit.';
  let ts = `// ${head}\nexport type SchemaType = 'object' | 'array' | 'string' | 'number' | 'integer' | 'boolean' | 'null';\nexport type SchemaLiteral = string | number | boolean | null;\n/** Shared model/provider vocabulary; executable profiles refuse unsupported features explicitly. */\nexport interface SchemaDefinition {\n`;
  const types = {
    types: 'SchemaType | readonly SchemaType[]',
    text: 'string',
    map: 'Readonly<Record<string, SchemaDefinition>>',
    strings: 'readonly string[]',
    rule: 'boolean | SchemaDefinition',
    schema: 'SchemaDefinition',
    schemas: 'readonly SchemaDefinition[]',
    literals: 'readonly SchemaLiteral[]',
    literal: 'SchemaLiteral',
    number: 'number',
    integer: 'number',
    boolean: 'boolean',
  };
  for (const [key, kind] of Object.entries(fields))
    ts += `  readonly ${JSON.stringify(key)}?: ${types[kind]};\n`;
  ts +=
    '}\nexport const SCHEMA_FIELDS = ' +
    JSON.stringify(fields) +
    ' as const;\n';
  let py = `# ${head}\nfrom __future__ import annotations\nfrom dataclasses import dataclass\nfrom typing import Literal, Mapping, cast\nfrom ._values import UNSET, Unset\nSchemaType = Literal["object", "array", "string", "number", "integer", "boolean", "null"]\nSchemaLiteral = str | int | float | bool | None\n@dataclass(frozen=True, kw_only=True)\nclass SchemaDefinition:\n    \"\"\"Shared schema vocabulary. Decode/freeze at the provider boundary before use.\"\"\"\n`;
  const pyt = {
    types: 'SchemaType | tuple[SchemaType, ...]',
    text: 'str',
    map: 'Mapping[str, SchemaDefinition]',
    strings: 'tuple[str, ...]',
    rule: 'bool | SchemaDefinition',
    schema: 'SchemaDefinition',
    schemas: 'tuple[SchemaDefinition, ...]',
    literals: 'tuple[SchemaLiteral, ...]',
    literal: 'SchemaLiteral',
    number: 'float',
    integer: 'int',
    boolean: 'bool',
  };
  const pyName = (key) =>
    ['type', 'if', 'else', 'not', 'const', 'default', 'enum'].includes(
      snake(key),
    )
      ? snake(key) + '_'
      : snake(key);
  for (const [key, kind] of Object.entries(fields))
    py += `    ${pyName(key)}: ${pyt[kind]} | Unset = UNSET\n`;
  py +=
    '\ndef schema_from_fields(fields: Mapping[str, object]) -> SchemaDefinition:\n    """Codec-only construction after every keyword has been decoded and checked."""\n    return SchemaDefinition(\n';
  for (const [key, kind] of Object.entries(fields))
    py += `        ${pyName(key)}=cast("${pyt[kind]} | Unset", fields.get("${key}", UNSET)),\n`;
  py += '    )\n';
  py +=
    'SCHEMA_FIELDS: dict[str, tuple[str, str]] = ' +
    JSON.stringify(
      Object.fromEntries(
        Object.entries(fields).map(([key, kind]) => [key, [pyName(key), kind]]),
      ),
    )
      .replace(/\[/g, '(')
      .replace(/\]/g, ')') +
    '\n';
  let go = `// ${head}\npackage plowshare\n// SchemaDefinition is the shared model/provider vocabulary. Codec validation precedes effects.\ntype SchemaDefinition struct {\n`;
  const got = {
    types: '*SchemaTypes',
    text: '*string',
    map: 'map[string]*SchemaDefinition',
    strings: '[]string',
    rule: '*SchemaRule',
    schema: '*SchemaDefinition',
    schemas: '[]*SchemaDefinition',
    literals: '[]ToolValue',
    literal: '*ToolValue',
    number: '*float64',
    integer: '*int',
    boolean: '*bool',
  };
  for (const [key, kind] of Object.entries(fields))
    go += `\t${pascal(key)} ${got[kind]} \`json:"${key},omitempty"\`\n`;
  go += '}\n';
  let cs = `// ${head}\n#nullable enable\nusing System.Text.Json.Serialization;\nnamespace Plowshare.Sdk;\n/// <summary>Shared model/provider vocabulary; codecs validate before external effects.</summary>\npublic sealed record SchemaDefinition {\n`;
  const cst = {
    types: 'SchemaTypes?',
    text: 'string?',
    map: 'IReadOnlyDictionary<string, SchemaDefinition>?',
    strings: 'IReadOnlyList<string>?',
    rule: 'SchemaRule?',
    schema: 'SchemaDefinition?',
    schemas: 'IReadOnlyList<SchemaDefinition>?',
    literals: 'IReadOnlyList<ToolValue>?',
    literal: 'ToolValue?',
    number: 'double?',
    integer: 'int?',
    boolean: 'bool?',
  };
  for (const [key, kind] of Object.entries(fields))
    cs += `    [JsonPropertyName("${key}"), JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)] public ${cst[kind]} ${pascal(key)} { get; init; }\n`;
  cs += '}\n';
  return {
    'sdk/typescript/src/operations/schema-definition.ts': ts,
    'sdk/python/src/plowshare/schema_definition.py': py,
    'sdk/go/schema_definition_generated.go': go,
    'sdk/dotnet/Plowshare.Sdk/SchemaDefinition.g.cs': cs,
  };
}
