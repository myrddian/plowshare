/** Generate native DTOs from the owning TypeScript contract graph. Wire values stay in codecs. */
import { OPERATION_SCHEMAS } from '../sdk/typescript/build/operations/operation-schemas.js';
import { constrain } from './native-sdk-constraints.mjs';
const quote = JSON.stringify;
const pascal = (s) =>
  s
    .replace(/[^a-zA-Z0-9]+/g, ' ')
    .split(' ')
    .filter(Boolean)
    .map((s) => s[0].toUpperCase() + s.slice(1))
    .join('');
const snake = (s) =>
  s
    .replace(/([a-z0-9])([A-Z])/g, '$1_$2')
    .replace(/[^a-zA-Z0-9]+/g, '_')
    .toLowerCase();
const pyField = (s) =>
  [
    'from',
    'type',
    'class',
    'is',
    'in',
    'global',
    'async',
    'await',
    'None',
    'True',
    'False',
  ].includes(snake(s))
    ? snake(s) + '_'
    : snake(s);
const id = (r) => r.$ref.replace('#/$defs/', '');
const defs = OPERATION_SCHEMAS.$defs;
const operations = Object.keys(OPERATION_SCHEMAS.inputs).sort();
const names = new Map(),
  used = new Set(['Request', 'Reply', 'ServerPush', 'Unit', 'Null', 'Unset']);
function name(key, hint) {
  if (names.has(key)) return names.get(key);
  const preferred =
    (defs[key].title ?? hint) +
    (defs[key].type === 'object' && !dictionary(defs[key]) ? 'Dto' : '');
  let chosen = pascal(preferred),
    n = 2;
  if (!chosen || /^\d/.test(chosen)) chosen = 'Value' + chosen;
  const base = chosen;
  while (used.has(chosen)) chosen = base + n++;
  names.set(key, chosen);
  used.add(chosen);
  const s = defs[key];
  if (s.properties)
    for (const [field, r] of Object.entries(s.properties))
      name(id(r), chosen + pascal(field));
  if (s.items) name(id(s.items), chosen + 'Item');
  if (s.prefixItems)
    s.prefixItems.forEach((r, i) => name(id(r), chosen + 'Item' + (i + 1)));
  if (typeof s.additionalProperties === 'object')
    name(id(s.additionalProperties), chosen + 'Entry');
  if (s.anyOf)
    s.anyOf.forEach((r, i) => name(id(r), chosen + 'Variant' + (i + 1)));
  return chosen;
}
// Prefer domain names over operation-specific names for shared nested values.
for (const [k, s] of Object.entries(defs)) if (s.title) name(k, s.title);
for (const op of operations) {
  name(id(OPERATION_SCHEMAS.inputs[op]), pascal(op) + 'Payload');
  name(id(OPERATION_SCHEMAS.results[op]), pascal(op) + 'Result');
}
name(id(OPERATION_SCHEMAS.pushes), 'Notification');
function simple(s) {
  if ('const' in s) return typeof s.const;
  if (s.type && !['object', 'array'].includes(s.type)) return s.type;
  if (s.optional || s.forbidden) return 'null';
  if (s.anyOf && s.anyOf.every((r) => simple(defs[id(r)]) === 'boolean'))
    return 'boolean';
  if (
    s.anyOf &&
    s.anyOf.every(
      (r) => 'const' in defs[id(r)] && typeof defs[id(r)].const === 'string',
    )
  )
    return 'string';
}
function dictionary(s) {
  return (
    s.type === 'object' &&
    !Object.keys(s.properties ?? {}).length &&
    typeof s.additionalProperties === 'object'
  );
}
function typ(k, lang, stack = new Set()) {
  const s = defs[k],
    v = simple(s);
  if (lang === 'py' && 'const' in s)
    return `Literal[${typeof s.const === 'boolean' ? (s.const ? 'True' : 'False') : quote(s.const)}]`;
  if (lang === 'py' && v === 'string' && s.anyOf)
    return `Literal[${s.anyOf.map((r) => quote(defs[id(r)].const)).join(', ')}]`;
  if (v)
    return {
      py: { string: 'str', number: 'float', boolean: 'bool', null: 'None' },
      go: {
        string: 'string',
        number: 'float64',
        boolean: 'bool',
        null: 'Unit',
      },
      cs: { string: 'string', number: 'double', boolean: 'bool', null: 'Unit' },
    }[lang][v];
  if (s.type === 'array') {
    if (s.prefixItems)
      return lang === 'py'
        ? 'tuple[' +
            s.prefixItems.map((r) => typ(id(r), lang, stack)).join(', ') +
            ']'
        : names.get(k);
    return lang === 'py'
      ? `tuple[${typ(id(s.items), lang, stack)}, ...]`
      : lang === 'go'
        ? `[]${typ(id(s.items), lang, stack)}`
        : `IReadOnlyList<${typ(id(s.items), lang, stack)}>`;
  }
  if (dictionary(s))
    return lang === 'py'
      ? `Mapping[str, ${typ(id(s.additionalProperties), lang, stack)}]`
      : lang === 'go'
        ? `map[string]${typ(id(s.additionalProperties), lang, stack)}`
        : `IReadOnlyDictionary<string, ${typ(id(s.additionalProperties), lang, stack)}>`;
  return names.get(k);
}
const classes = [...names].filter(([k]) => {
  const s = defs[k];
  return (
    !simple(s) &&
    !dictionary(s) &&
    (s.type === 'object' || s.anyOf || s.prefixItems)
  );
});
const header = 'Generated by scripts/generate-sdk-contracts.mjs; do not edit.';
const fields = (k) =>
  Object.entries(defs[k].properties ?? {}).filter(
    ([, r]) => !defs[id(r)].forbidden,
  );
function pyClass(n, k, base = '') {
  const required = new Set(defs[k].required ?? []);
  return (
    `@dataclass(frozen=True, kw_only=True)\nclass ${n}${base}:\n    """Validated fields of the ${defs[k].title ?? n} protocol contract."""\n` +
    fields(k)
      .map(
        ([f, r]) =>
          `    ${pyField(f)}: ${typ(id(r), 'py')}${required.has(f) ? '' : ' | Unset = UNSET'}\n`,
      )
      .join('')
  );
}
export function nativeContracts() {
  let py = `# ${header}\nfrom __future__ import annotations\nfrom dataclasses import dataclass\nfrom typing import ClassVar, Generic, Literal, Mapping, TypeAlias, TypeVar\nfrom ._values import UNSET, Unset\nT = TypeVar("T", covariant=True)\nclass Request(Generic[T]):\n    """An operation paired with its validated result type; only generated requests are accepted."""\n    operation: ClassVar[str]\n`;
  for (const [k, n] of classes) {
    const s = defs[k];
    if (s.type === 'object') py += '\n' + pyClass(n, k);
    else if (s.anyOf)
      py += `\n${n}: TypeAlias = ${quote(s.anyOf.map((r) => typ(id(r), 'py')).join(' | '))}\n`;
    else
      py += `\n${n}: TypeAlias = ${quote(`tuple[${s.prefixItems.map((r) => typ(id(r), 'py')).join(', ')}]`)}\n`;
  }
  for (const op of operations) {
    const result = typ(id(OPERATION_SCHEMAS.results[op]), 'py'),
      n = pascal(op) + 'Request';
    const key = id(OPERATION_SCHEMAS.inputs[op]);
    py +=
      '\n' +
      (defs[key].anyOf
        ? `@dataclass(frozen=True, kw_only=True)\nclass ${n}(Request[${result}]):\n    selection: ${typ(key, 'py')}\n`
        : pyClass(n, key, `(Request[${result}])`)) +
      `    operation: ClassVar[str] = ${quote(op)}\n`;
  }
  py += `\nServerPush: TypeAlias = "${typ(id(OPERATION_SCHEMAS.pushes), 'py')}"\n`;
  py +=
    '\n_MODELS = {\n' +
    classes
      .filter(([k]) => defs[k].type === 'object')
      .map(([k, n]) => `    ${quote(k)}: ${n},\n`)
      .join('') +
    '}\n';
  py +=
    '\n_REQUESTS = {\n' +
    operations
      .map((op) => `    ${pascal(op)}Request: ${quote(op)},\n`)
      .join('') +
    '}\n';
  py +=
    '\n_FIELDS = {\n' +
    classes
      .filter(([k]) => defs[k].type === 'object')
      .map(
        ([k, n]) =>
          `    ${n}: {${fields(k)
            .map(([f]) => quote(f) + ': ' + quote(pyField(f)))
            .join(', ')}},\n`,
      )
      .join('') +
    operations
      .map(
        (op) =>
          `    ${pascal(op)}Request: {${fields(id(OPERATION_SCHEMAS.inputs[op]))
            .map(([f]) => quote(f) + ': ' + quote(pyField(f)))
            .join(', ')}},\n`,
      )
      .join('') +
    '}\n';
  let go = `// ${header}\npackage plowshare\nimport ("context"; "encoding/json"; "errors")\n`;
  let cs = `// ${header}\nusing System.Text.Json;\nusing System.Text.Json.Serialization;\nnamespace Plowshare.Sdk;\n`;
  function objectModels(n, k) {
    const required = new Set(defs[k].required ?? []);
    go +=
      `\n// ${n} is the explicit ${defs[k].title ?? n} protocol shape.\ntype ${n} struct {\n` +
      fields(k)
        .map(
          ([f, r]) =>
            ` ${pascal(f)} ${required.has(f) ? '' : '*'}${typ(id(r), 'go')} ${'`json:' + quote(f + (required.has(f) ? '' : ',omitempty')) + '`'}\n`,
        )
        .join('') +
      '}\n';
    cs +=
      `\n/// <summary>Fields of the ${defs[k].title ?? n} protocol contract.</summary>\npublic sealed record ${n} {\n` +
      fields(k)
        .map(
          ([f, r]) =>
            ` [JsonPropertyName(${quote(f)})] ${required.has(f) ? '' : '[JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingDefault)] '}public ${required.has(f) ? 'required ' : ''}${required.has(f) ? typ(id(r), 'cs') : `Optional<${typ(id(r), 'cs')}>`} ${pascal(f)} { get; init; }\n`,
        )
        .join('') +
      '}\n';
  }
  for (const [k, n] of classes) {
    const s = defs[k];
    if (s.type === 'object') {
      objectModels(n, k);
      continue;
    }
    const variants = s.anyOf ?? s.prefixItems;
    if (s.prefixItems) {
      go +=
        `\n// ${n} is an ordered protocol tuple.\ntype ${n} struct {\n` +
        variants.map((r, i) => ` Item${i + 1} ${typ(id(r), 'go')}\n`).join('') +
        '}\n' +
        `func (v ${n}) MarshalJSON() ([]byte,error) { return json.Marshal([]any{${variants.map((_, i) => `v.Item${i + 1}`).join(',')}}) }\nfunc(v *${n}) UnmarshalJSON(data []byte) error { var a []json.RawMessage; if err:=json.Unmarshal(data,&a);err!=nil{return err}; if len(a)!=${variants.length}{return errors.New("invalid tuple")}; ` +
        variants
          .map(
            (_, i) =>
              `if err:=json.Unmarshal(a[${i}],&v.Item${i + 1});err!=nil{return err};`,
          )
          .join('') +
        ' return nil }\n';
      cs += `\n[JsonConverter(typeof(${n}Converter))]\npublic sealed record ${n}(${variants.map((r, i) => `${typ(id(r), 'cs')} Item${i + 1}`).join(', ')});\ninternal sealed class ${n}Converter : JsonConverter<${n}> {\n public override bool HandleNull => true;\n public override ${n} Read(ref Utf8JsonReader reader, Type type, JsonSerializerOptions options) { using var document=JsonDocument.ParseValue(ref reader);var a=document.RootElement; if(a.ValueKind!=JsonValueKind.Array || a.GetArrayLength()!=${variants.length}) throw new JsonException("Invalid tuple");return new ${n}(${variants.map((r, i) => `a[${i}].Deserialize<${typ(id(r), 'cs')}>(options)!`).join(', ')}); }\n public override void Write(Utf8JsonWriter writer, ${n} value, JsonSerializerOptions options) { writer.WriteStartArray();${variants.map((_, i) => `JsonSerializer.Serialize(writer,value.Item${i + 1},options);`).join('')}writer.WriteEndArray(); }\n}\n`;
      continue;
    }
    go +=
      `\n// ${n} is a closed union: exactly one variant must be selected.\ntype ${n} struct {\n` +
      variants
        .map((r, i) => ` Variant${i + 1} *${typ(id(r), 'go')}\n`)
        .join('') +
      '}\n';
    go +=
      `func(v ${n}) MarshalJSON() ([]byte,error) { var chosen any; count:=0; ` +
      variants
        .map(
          (r, i) =>
            `if v.Variant${i + 1}!=nil{chosen=v.Variant${i + 1};count++};`,
        )
        .join('') +
      'if count!=1{return nil,errors.New("select exactly one union variant")};return json.Marshal(chosen) }\n';
    go +=
      `func(v *${n}) UnmarshalJSON(data []byte) error { *v=${n}{}; ` +
      variants
        .map(
          (r, i) =>
            `if matches(${quote(id(r))},data) { var chosen ${typ(id(r), 'go')}; if err:=json.Unmarshal(data,&chosen);err!=nil{return err};v.Variant${i + 1}=&chosen;return nil };`,
        )
        .join('') +
      'return errors.New("invalid union") }\n';
    cs +=
      `\n/// <summary>A closed protocol union. Select one variant using its factory.</summary>\n[JsonConverter(typeof(${n}Converter))]\npublic sealed record ${n} {\n private ${n}() {}\n` +
      variants
        .map(
          (r, i) =>
            ` public Optional<${typ(id(r), 'cs')}> Variant${i + 1} {get; private init;}\n public static ${n} FromVariant${i + 1}(${typ(id(r), 'cs')} value)=>new() {Variant${i + 1}=new(value)};\n`,
        )
        .join('') +
      '}\n';
    cs +=
      `internal sealed class ${n}Converter : JsonConverter<${n}> {\n public override bool HandleNull => true;\n public override ${n} Read(ref Utf8JsonReader reader,Type type,JsonSerializerOptions options) {using var document=JsonDocument.ParseValue(ref reader);var value=document.RootElement;` +
      variants
        .map(
          (r, i) =>
            `if(Codec.Matches(${quote(id(r))},value))return ${n}.FromVariant${i + 1}(value.Deserialize<${typ(id(r), 'cs')}>(options)!);`,
        )
        .join('') +
      'throw new JsonException("Invalid union");}\n';
    cs +=
      ` public override void Write(Utf8JsonWriter writer,${n} value,JsonSerializerOptions options) {` +
      variants
        .map(
          (_, i) =>
            `if(value.Variant${i + 1}.IsSet){JsonSerializer.Serialize(writer,value.Variant${i + 1}.Value,options);return;}`,
        )
        .join('') +
      'throw new JsonException("Select a union variant");}\n}\n';
  }
  for (const op of operations) {
    const n = pascal(op) + 'Request',
      k = id(OPERATION_SCHEMAS.inputs[op]),
      gresult = typ(id(OPERATION_SCHEMAS.results[op]), 'go'),
      cresult = typ(id(OPERATION_SCHEMAS.results[op]), 'cs');
    if (defs[k].anyOf) {
      go += `\ntype ${n} = ${typ(k, 'go')}\n`;
      cs += `\npublic sealed record ${n}(${typ(k, 'cs')} Selection);\n`;
    } else objectModels(n, k);
    go += `\n// ${pascal(op)} validates before submission and returns the paired result DTO.\nfunc(c *Client) ${pascal(op)}(ctx context.Context, request ${n}) (Reply[${gresult}],error) { return requestTyped[${gresult}](ctx,c,${quote(op)},request) }\n`;
    cs += `public static partial class Operations { public static Task<Reply<${cresult}>> ${pascal(op)}Async(this Client client,${n} request,CancellationToken cancellationToken=default)=>client.RequestTypedAsync<${defs[k].anyOf ? typ(k, 'cs') : n},${cresult}>(${quote(op)},${defs[k].anyOf ? 'request.Selection' : 'request'},cancellationToken); }\n`;
  }
  go += `\n// ServerPush is a validated notification; reconcile durable state through operations.\ntype ServerPush = ${typ(id(OPERATION_SCHEMAS.pushes), 'go')}\n`;
  cs += `\npublic sealed record ServerPush(${typ(id(OPERATION_SCHEMAS.pushes), 'cs')} Notification);\n`;
  const checkedSchemas = constrain(structuredClone(OPERATION_SCHEMAS));
  return {
    'sdk/python/src/plowshare/contracts.py': py,
    'sdk/go/contracts_generated.go': go,
    'sdk/dotnet/Plowshare.Sdk/Contracts.g.cs': cs,
    'sdk/python/src/plowshare/_schemas.json':
      JSON.stringify(checkedSchemas) + '\n',
    'sdk/go/schemas.json': JSON.stringify(checkedSchemas) + '\n',
    'sdk/dotnet/Plowshare.Sdk/Schemas.json':
      JSON.stringify(checkedSchemas) + '\n',
  };
}
