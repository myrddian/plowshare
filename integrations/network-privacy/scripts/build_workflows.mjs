import { createRequire } from 'node:module';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

// Source deployment has a 128 KiB package limit. Keep readable, documented
// authoring files outside the deployable tree; ship deterministic compact ESM.
// Production collectors need neither Node nor a compiler. Checks verify the
// tracked artifacts against the repository's existing pinned esbuild toolchain.
const repository = new URL('../../../', import.meta.url);
const require = createRequire(new URL('plowshare-desktop/package.json', repository));
const { transform } = require('esbuild');
const sources = new URL('./orchestrations/', import.meta.url);
for (const name of (await readdir(sources)).filter(name => name.endsWith('.js')).sort()) {
  const source = await readFile(new URL(name, sources), 'utf8');
  if (!source.startsWith('// plowshare-script v1')) throw new Error(`Missing script marker: ${name}`);
  const result = await transform(source, { minify: true, format: 'esm', target: 'es2022',
    sourcefile: fileURLToPath(new URL(name, sources)) });
  // The existing offline setup/upgrade binds this one manifest value using an
  // explicit textual marker. Preserve that contract after code generation.
  if ((result.code.match(/model:"reasoning"/g) || []).length !== 1) throw new Error(`Unexpected model declaration: ${name}`);
  const body = result.code.replace('model:"reasoning"', "model: 'reasoning'");
  const output = '// plowshare-script v1\n// Generated by scripts/build_workflows.mjs; edit scripts/orchestrations/' + name + '.\n' + body;
  const target = new URL('../network-privacy-watch/orchestrations/' + name, import.meta.url);
  if (process.argv.includes('--check')) {
    if (await readFile(target, 'utf8') !== output) throw new Error(`Stale workflow: ${name}; run scripts/build_workflows.mjs.`);
  } else await writeFile(target, output);
}
console.log('Application workflow artifacts are current.');
