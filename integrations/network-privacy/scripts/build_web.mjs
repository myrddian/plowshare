import { createRequire } from 'node:module';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

// Generation uses the repository's existing esbuild toolchain. Installed Python
// collectors serve the checked-in bundle; they need neither Node nor a CDN.
const repository = new URL('../../../', import.meta.url);
const require = createRequire(new URL('plowshare-desktop/package.json', repository));
const { build } = require('esbuild');
const target = new URL('../src/plowshare_privacy/web/markdown.js', import.meta.url);
const result = await build({
  absWorkingDir: fileURLToPath(repository),
  entryPoints: [fileURLToPath(new URL('./markdown-view.mjs', import.meta.url))],
  alias: {
    'plowshare-client-ts/operations/markdown': fileURLToPath(new URL('sdk/typescript/src/operations/markdown.ts', repository)),
  },
  bundle: true,
  format: 'iife',
  globalName: 'PrivacyMarkdown',
  platform: 'browser',
  target: 'es2022',
  write: false,
  banner: {js: '// Generated by integrations/network-privacy/scripts/build_web.mjs; do not edit.'},
});
const output = result.outputFiles[0].text;
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== output) throw new Error('Privacy Markdown bundle is stale; run scripts/build_web.mjs.');
  console.log('Privacy Markdown bundle is current.');
} else {
  await writeFile(target, output);
  console.log('Generated privacy Markdown bundle from the public SDK grammar.');
}
