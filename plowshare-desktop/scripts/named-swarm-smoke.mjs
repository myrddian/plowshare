import { _electron as electron, expect } from 'playwright/test';
import executablePath from 'electron';
import { mkdtemp, mkdir, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import assert from 'node:assert/strict';
import { protocolFixture } from './protocol-fixture.mjs';
const profile = await mkdtemp(join(tmpdir(), 'plowshare-named-swarm-'));
const env = {...process.env,PLOWSHARE_DESKTOP_CONFIG:join(profile,'config'),PLOWSHARE_CONFIG_DIR:join(profile,'credentials'),PLOWSHARE_DESKTOP_PROFILE:profile};
delete env.ELECTRON_RUN_AS_NODE;
const fixture = await protocolFixture({boardProject:'Empty workspace'});
let app;
try {
  app = await electron.launch({executablePath,args:[resolve('.')],env});
  const page = await app.firstWindow();
  const errors=[]; page.on('pageerror',error=>errors.push(error.message));
  await page.locator('#connect-sidebar').click(); await page.locator('#server-url').fill(fixture.base);
  await page.locator('#handle').fill('fixture'); await page.locator('#password').fill('fixture-password'); await page.locator('#submit-connection').click();
  await expect(page.locator('#connection-label')).toHaveText(/ · Connected$/);
  const opened=app.waitForEvent('window'); await page.locator('#board-open').click(); const board=await opened;
  board.on('pageerror',error=>errors.push(error.message));
  await board.locator('#board-create-open').click(); await board.locator('#create-project').selectOption('Empty workspace');
  await expect(board.locator('#create-swarm option')).toHaveCount(3);
  await board.locator('#create-swarm').selectOption('incident'); await board.locator('#create-title').fill('Investigate telemetry');
  await board.locator('#create-body').fill('Review supplied scan evidence.');
  fixture.setRefusePost(true); await board.locator('#create-submit').click(); await expect(board.locator('#create-error')).toContainText('draft and request identity are retained');
  const request=fixture.frames.filter(frame=>frame.type==='board.open').at(-1);
  assert.equal(request.payload.swarm,'incident');
  await board.reload(); await board.locator('#board-create-open').click();
  await expect(board.locator('#create-swarm')).toHaveValue('incident');
  fixture.setSwarmTypes([]); await board.locator('#create-swarm-refresh').click();
  await expect(board.locator('#create-swarm-status')).toContainText('No swarm types');
  await expect(board.locator('#create-swarm')).toHaveValue('incident');
  fixture.setRefuseBoard(true); await board.locator('#create-swarm-refresh').click();
  await expect(board.locator('#create-swarm-status')).toContainText('temporarily unavailable');
  fixture.setRefuseBoard(false); fixture.setRefusePost(false);
  await board.setViewportSize({width:920,height:680});
  assert.equal(await board.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await mkdir('build/smoke',{recursive:true}); await board.screenshot({path:'build/smoke/named-swarm-draft.png'});
  await board.locator('#create-submit').click(); await expect(board.locator('#board-create-dialog')).not.toBeVisible();
  await expect(board.locator('#board-detail h2')).toHaveText('Investigate telemetry');
  await expect(board.locator('#board-detail .eyebrow').first()).toContainText('incident');
  const requests=fixture.frames.filter(frame=>frame.type==='board.open');
  assert.equal(requests.length,2); assert.equal(requests[1].payload.requestId,request.payload.requestId);
  assert.deepEqual(errors,[]);
  console.log('Named swarm desktop smoke passed: selection, saved draft, unavailable and empty catalogs, receipt identity, selected-topic display and compact layout.');
} finally {await app?.close();await fixture.close();await rm(profile,{recursive:true,force:true});}
