import { _electron as electron, expect } from 'playwright/test';
import executablePath from 'electron';
import { mkdtemp, mkdir, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import assert from 'node:assert/strict';
import { protocolFixture } from './protocol-fixture.mjs';

const profile = await mkdtemp(join(tmpdir(), 'plowshare-navigation-'));
const fixture = await protocolFixture({ stageNavigation: true });
const env = { ...process.env, PLOWSHARE_CONFIG_DIR: join(profile,'credentials'), PLOWSHARE_DESKTOP_CONFIG:join(profile,'config'), PLOWSHARE_DESKTOP_PROFILE:profile };
delete env.ELECTRON_RUN_AS_NODE;
let app;
try {
  app = await electron.launch({executablePath,args:[resolve('.')],env});
  const main = await app.firstWindow(), errors = [];
  main.on('pageerror',error=>errors.push(error.message));
  await main.locator('#connect-sidebar').click(); await main.locator('#server-url').fill(fixture.base);
  await main.locator('#handle').fill('fixture'); await main.locator('#password').fill('fixture-password');
  await main.locator('#submit-connection').click(); await expect(main.locator('#connection-label')).toHaveText('Connected');
  const activityOpening = app.waitForEvent('window'); await main.evaluate(()=>window.plowshare.request({action:'activity',view:'runs'}));
  const runs = await activityOpening; runs.on('pageerror',error=>errors.push(error.message));
  await expect(runs.locator('[data-run-stage="reading"]')).toBeEnabled();
  await expect(runs.locator('[data-run-stage="objective_review"]')).toBeEnabled();
  const review = runs.locator('.activity-stages li').filter({has:runs.locator('[data-run-stage="objective_review"]')});
  await expect(review).toContainText('Review marker.'); await expect(review.locator('#run-answer-send')).toBeEnabled();
  assert.equal(await runs.locator('#activity-detail').evaluate(node=>node.textContent.split('Review marker.').length-1),1);
  await expect(runs.locator('.run-agent-tree')).toHaveCount(0);
  await mkdir('build/smoke',{recursive:true}); await runs.screenshot({path:'build/smoke/run-navigation.png'});
  await review.scrollIntoViewIfNeeded(); await runs.screenshot({path:'build/smoke/stage-question.png'});
  await runs.locator('#activity-detail').evaluate(node=>{node.scrollTop=0;});
  await runs.setViewportSize({width:860,height:620}); await runs.screenshot({path:'build/smoke/run-navigation-compact.png'});
  const stageOpening = app.waitForEvent('window'); await runs.locator('[data-run-stage="reading"]').click();
  const stage = await stageOpening; stage.on('pageerror',error=>errors.push(error.message));
  await expect(stage.locator('#trajectory-scope')).toContainText('Stage: reading');
  await expect(stage.locator('#trajectory-rows')).toContainText('Reading stage work.');
  await expect(stage.locator('#trajectory-rows')).not.toContainText('Later review stage work.');
  await expect(stage.locator('#trajectory-rows [data-step="1"]')).toHaveCount(1);
  assert.ok(fixture.frames.some(frame=>frame.type==='conversation.trajectory'&&frame.payload.conversation==='fixture-conductor'&&frame.payload.before!==undefined));
  await stage.locator('.trajectory-row[data-step="1"]').click();
  await expect(stage.locator('#trajectory-detail-content')).toContainText('Reading stage work.');
  await expect(stage.locator('#trajectory-detail-content')).toContainText('Folded into model summary #160');
  const childOpening = app.waitForEvent('window'); await stage.locator('.step-trajectory-link.row[data-delegate-step="5:delegate-one"]').click();
  const child = await childOpening; child.on('pageerror',error=>errors.push(error.message));
  await expect(child.locator('#trajectory-conversation')).toHaveText('fixture-delegate-one');
  await child.locator('.trajectory-row[data-step="1:nested-editor"]').click();
  await expect(child.locator('#trajectory-detail-heading [data-delegate-step="1:nested-editor"]')).toHaveCount(1);
  const nestedOpening = app.waitForEvent('window'); await child.locator('#trajectory-detail-heading [data-delegate-step="1:nested-editor"]').click();
  const nested = await nestedOpening; await expect(nested.locator('#trajectory-detail-content')).toContainText('Nested editor verification.');
  await assert.rejects(child.evaluate(()=>window.plowshare.request({action:'delegate-trajectory',conversation:'foreign',step:'1:nested-editor'})),/this trajectory/);
  await assert.rejects(runs.evaluate(()=>window.plowshare.request({action:'delegate-trajectory',conversation:'fixture-conductor',step:'invented'})),/recorded delegation/);
  await assert.rejects(main.evaluate(()=>window.plowshare.request({action:'run-stage-trajectory',id:'fixture-old-root',stage:'reading'})),/Open Activity/);
  await stage.locator('.trajectory-row[data-step="5:delegate-one"]').click();
  await expect(stage.locator('.trajectory-row[data-step="5:delegate-one"] .delegation-direction')).toHaveText(['>', '<']);
  await expect(stage.locator('#trajectory-detail-heading .step-trajectory-link')).toHaveText('Trajectory');
  await expect(stage.locator('#trajectory-agents')).toHaveCount(0);
  await stage.screenshot({path:'build/smoke/stage-trajectory.png'}); await child.screenshot({path:'build/smoke/delegated-trajectory.png'});
  await nested.close(); await child.close();
  const secondOpening = app.waitForEvent('window'); await stage.locator('.step-trajectory-link.row[data-delegate-step="8:delegate-two"]').click();
  const second = await secondOpening; await expect(second.locator('#trajectory-conversation')).toHaveText('fixture-delegate-two');
  await expect(second.locator('#trajectory-detail-content')).toContainText('Second analyst work.');
  const callerOpening = app.waitForEvent('window'); await runs.locator('[data-run-actor="caller"]').click();
  const caller = await callerOpening; await caller.locator('.trajectory-row[data-step="1:research-start"]').click();
  await expect(caller.locator('#trajectory-detail-heading .step-trajectory-link')).toHaveText('Trajectory');
  const conductorOpening = app.waitForEvent('window'); await caller.locator('#trajectory-detail-heading .step-trajectory-link').click();
  const conductor = await conductorOpening; await expect(conductor.locator('#trajectory-conversation')).toHaveText('fixture-conductor');
  await caller.screenshot({path:'build/smoke/orchestration-call-link.png'});
  assert.equal(fixture.frames.some(frame=>frame.type==='agent.run'),false); assert.deepEqual(errors,[]);
  console.log('PASS: stage-scoped trajectories load older work, questions appear once in their stage, two calls to the same agent open distinct children, nested trajectories navigate, unrelated requests are rejected, no paid work is replayed.');
} finally { if (app) await app.close(); await fixture.close(); await rm(profile,{recursive:true,force:true}); }
