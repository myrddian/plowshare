import { _electron as electron, expect } from 'playwright/test';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { protocolFixture } from './protocol-fixture.mjs';

const profile = await mkdtemp(join(tmpdir(), 'plowshare-info-board-'));
const command = { command:'/skill:review', aliases:[], kind:'skill', name:'review', description:'Review the change', argumentHint:'Change to review', executor:'interlocutor', mode:'DIRECT', tier:'PROJECT', hash:'fixture-hash' };
const fixture = await protocolFixture({ boardProject:'Empty workspace', agentRoster:async () => [{ name:'fixture-bot', bot:true, served:true, preferred:true, model:'fixture-model', description:'Bot', tools:[], commands:[command] }] });
const env = { ...process.env, PLOWSHARE_DESKTOP_PROFILE:profile, PLOWSHARE_DESKTOP_CONFIG:join(profile,'config'), PLOWSHARE_CONFIG_DIR:join(profile,'credentials') }; delete env.ELECTRON_RUN_AS_NODE;
let app;
try {
  const packaged = process.env.PLOWSHARE_PACKAGED_EXECUTABLE;
  app = await electron.launch({ executablePath:packaged ?? (await import('electron')).default, args:packaged ? [] : [resolve('.')], env });
  const main = await app.firstWindow(), errors=[];
  main.on('pageerror', error => errors.push(error.message));
  await main.evaluate(base => window.plowshare.request({ action:'connect', base, handle:'fixture', password:'fixture-password' }), fixture.base);
  await main.locator('#conversations [data-conversation="fixture-first"]').click();
  await expect(main.locator('#inspector-toggle')).toHaveText('Info');
  await expect(main.locator('#inspector [role=tab]')).toHaveText(['Context','Commands','Files']);
  await expect(main.locator('#sidebar #agent-commands')).toHaveCount(0);
  await main.locator('#info-commands-tab').click();
  await expect(main.locator('#agent-commands')).toContainText('/skill:review');
  await expect(main.locator('#agent-commands summary')).toHaveCount(0);
  await expect(main.locator('#info-context')).toBeHidden();
  await main.locator('#info-commands-tab').press('ArrowRight');
  await expect(main.locator('#info-files-tab')).toBeFocused();
  await expect(main.locator('#info-files')).toContainText('Project file access');
  await expect(main.locator('#files-choose')).toBeVisible();
  await main.locator('#info-files-tab').press('Home');
  await expect(main.locator('#info-context-tab')).toBeFocused();
  await expect(main.locator('#inspector-content')).toContainText('Constructed projection');
  await mkdir('build/smoke', { recursive:true });
  await main.locator('#info-commands-tab').click();
  await main.screenshot({ path:'build/smoke/info-commands.png' });
  await main.locator('#inspector').screenshot({ path:'build/smoke/info-panel.png' });
  await main.locator('#info-files-tab').click();
  await main.screenshot({ path:'build/smoke/info-files.png' });

  const opening = app.waitForEvent('window'); await main.locator('#board-open').click(); const board = await opening;
  board.on('pageerror', error => errors.push(error.message));
  await expect(board.locator('#board-post-open')).toHaveText('Post to board');
  const contrast = await board.locator('#board-post-open').evaluate(element => {
    const style = getComputedStyle(element);
    const lum = color => color.match(/[\d.]+/g).slice(0,3).map(Number).map(v => v/255).map(v => v <= .04045 ? v/12.92 : ((v+.055)/1.055)**2.4).reduce((sum,v,i) => sum+v*[.2126,.7152,.0722][i],0);
    const a=lum(style.color), b=lum(style.backgroundColor); return (Math.max(a,b)+.05)/(Math.min(a,b)+.05);
  });
  assert.ok(contrast >= 4.5, `Post label contrast: ${contrast}`);
  await board.locator('#board-create-open').click();
  await board.locator('#create-project').selectOption('Empty workspace');
  await board.locator('#create-title').fill('A new project topic');
  await board.locator('#create-body').fill('Investigate the project topic.');
  await board.locator('#create-budget').fill('4');
  fixture.setRefusePost(true); await board.locator('#create-submit').click();
  await expect(board.locator('#create-error')).toContainText('request identity are retained');
  const first = fixture.frames.find(frame => frame.type === 'board.open');
  await board.locator('#board-create-close').click(); await board.locator('#board-create-open').click();
  await expect(board.locator('#create-body')).toHaveValue('Investigate the project topic.');
  fixture.setRefusePost(false); await board.locator('#create-submit').click();
  await expect(board.locator('#board-create-dialog')).toBeHidden();
  await expect(board.locator('#board-detail h2')).toHaveText('A new project topic');
  const retries = fixture.frames.filter(frame => frame.type === 'board.open');
  assert.equal(retries.length,2); assert.deepEqual(retries[1].payload,first.payload);
  assert.equal(first.payload.maxModelCalls,4);
  await board.locator('#board-post-open').click();
  await expect(board.locator('#post-topic')).toContainText('A new project topic');
  await board.locator('#post-body').fill('Follow-up from the person.'); await board.locator('#post-submit').click();
  await expect(board.locator('#post-notice')).toContainText('Posted to the board');
  await board.locator('#board-post-close').click();
  await expect(board.locator('#board-detail')).toContainText('Follow-up from the person.');
  await board.screenshot({ path:'build/smoke/board-new-topic.png' });
  assert.deepEqual(errors,[]);
  assert.deepEqual([...new Set(fixture.httpPaths)].sort(), ['/v1/auth/login','/v1/auth/refresh','/v1/auth/ticket']);
  console.log('PASS: readable Board Post button, explicit project topic creation, retained retry identity, selected new topic and follow-up post; Info Context/Commands/Files tabs, keyboard navigation, and no command dropdown in sidebar.');
} finally { await app?.close(); await fixture.close(); await rm(profile,{ recursive:true,force:true }); }
