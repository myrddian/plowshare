UPDATE firings f SET message_instance=i.id,topic=NULL,
 target=CASE WHEN f.status='queued' THEN 'conversation:'||i.conversation||':instance:'||i.id ELSE f.target END
 FROM message_instances i WHERE f.topic=i.former_topic;
UPDATE firings f SET message_position=p.position
 FROM message_cutover_publications p WHERE f.data->>'direct_message'=p.event_id;
CREATE INDEX firings_by_message_instance ON firings(message_instance) WHERE message_instance IS NOT NULL;
DROP TRIGGER relay_wake_changes ON firings;
CREATE TRIGGER relay_wake_changes AFTER INSERT ON firings
 FOR EACH ROW WHEN ((NEW.topic IS NOT NULL OR NEW.message_instance IS NOT NULL) AND NEW.status='queued')
 EXECUTE FUNCTION relay_capture_wake();
-- Re-keyed queued work receives an availability hint; it is still the very same durable firing.
INSERT INTO relay_source_events(topic,family,subject,state,context,occurred_at)
 SELECT 'message.wake.requested','WAKE_REQUESTED',id,'MESSAGE',target,arrived_at
 FROM firings WHERE message_instance IS NOT NULL AND status='queued';

CREATE OR REPLACE FUNCTION relay_capture_message_instance() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF TG_OP='INSERT' OR OLD.active IS DISTINCT FROM NEW.active OR OLD.is_default IS DISTINCT FROM NEW.is_default THEN
  INSERT INTO relay_source_events(topic,family,subject,state,context,related,occurred_at)
   VALUES('message.instance.changed','LIFECYCLE',NEW.id,
    CASE WHEN NEW.active THEN 'active' ELSE 'inactive' END,NEW.conversation,coalesce(NEW.former_topic,NEW.id),clock_timestamp());
 END IF;
 RETURN NEW;
END $$;
-- Public forum capture keeps its privacy fence for historical identifiers during cutover.
CREATE OR REPLACE FUNCTION relay_capture_board_topic() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE project_key BIGINT; event_topic TEXT;
BEGIN
    IF EXISTS(SELECT 1 FROM message_instances WHERE former_topic=NEW.id) THEN RETURN NEW; END IF;
    SELECT id INTO project_key FROM projects WHERE name=NEW.project;
    IF project_key IS NULL THEN RETURN NEW; END IF;
    IF TG_OP='INSERT' THEN event_topic='board.opened';
    ELSIF OLD.state IS DISTINCT FROM NEW.state AND NEW.state='closed' THEN event_topic='board.closed';
    END IF;
    IF event_topic IS NOT NULL THEN
        INSERT INTO relay_source_events(project_id,topic,family,subject,state,context,related,occurred_at)
        VALUES(project_key,event_topic,'LIFECYCLE',NEW.id,NEW.state,NEW.root,NEW.parent,
            COALESCE(NEW.closed_at,NEW.opened_at));
    END IF;
    IF TG_OP='UPDATE' AND OLD.resolution IS NULL AND NEW.resolution IS NOT NULL THEN
        INSERT INTO relay_source_events(project_id,topic,family,subject,state,context,related,occurred_at)
        VALUES(project_key,'board.resolved','LIFECYCLE',NEW.id,NEW.state,NEW.root,NEW.resolution,clock_timestamp());
    END IF;
    RETURN NEW;
END $$;
CREATE OR REPLACE FUNCTION relay_capture_board_message() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE project_key BIGINT; public_topic BOOLEAN;
BEGIN
    SELECT p.id,NOT EXISTS(SELECT 1 FROM message_instances i WHERE i.former_topic=t.id) INTO project_key,public_topic
      FROM board_topics t JOIN projects p ON p.name=t.project WHERE t.id=NEW.topic;
    IF public_topic AND project_key IS NOT NULL THEN
        INSERT INTO relay_source_events(project_id,topic,family,subject,state,context,related,occurred_at)
        VALUES(project_key,'board.message.posted','LIFECYCLE',NEW.id,NEW.kind,NEW.topic,NEW.reply_to,NEW.posted_at);
    END IF;
    RETURN NEW;
END $$;
