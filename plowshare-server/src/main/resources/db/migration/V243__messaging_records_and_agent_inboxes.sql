-- One project-readable topic and one leased consumer group per (account, project, definition).
CREATE TABLE message_agent_inboxes (
 account TEXT NOT NULL REFERENCES admins(handle) ON DELETE CASCADE,
 project_id BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
 project TEXT NOT NULL,
 agent TEXT NOT NULL,
 topic TEXT NOT NULL,
 retired_at TIMESTAMPTZ,
 PRIMARY KEY(account,project_id,agent),
 UNIQUE(project_id,topic)
);
INSERT INTO message_agent_inboxes(account,project_id,project,agent,topic)
 SELECT DISTINCT i.account,p.id,i.project,i.agent,
 'messaging.agent.'||encode(sha256(convert_to(i.account,'UTF8')),'hex')||'.'||encode(sha256(convert_to(i.agent,'UTF8')),'hex')
 FROM message_instances i JOIN projects p ON p.name=i.project;
INSERT INTO relay_topics(scope_key,project_id,name,payload_kind,retention_seconds)
 SELECT 'project:'||project_id,project_id,topic,'TEXT',2592000 FROM message_agent_inboxes;
INSERT INTO relay_subscriptions(scope_key,topic,subscriber,seen_through,seen_at)
 SELECT 'project:'||project_id,topic,'messaging.inbox',0,clock_timestamp() FROM message_agent_inboxes;

-- Migrate every retained thread before the new runtime can dispatch. Retained body references
-- preserve authored/generated historical text regardless of today's inline admission limit.
CREATE TEMP TABLE message_cutover_publications ON COMMIT DROP AS
 SELECT 'project:'||a.project_id AS scope_key,a.topic,m.id AS event_id,
  row_number() OVER(PARTITION BY a.project_id,a.topic ORDER BY m.seq) AS position,
  'messaging:'||encode(sha256(convert_to(i.account,'UTF8')),'hex') AS publisher,m.posted_at,
  jsonb_build_object('text',jsonb_build_object(
   'schema','plowshare-message/1','message',m.id,'sender',r.sender,'recipient',r.recipient,
   'body',jsonb_build_object('kind','retained','message',m.id),'reply_to',r.reply_to,
   'conversation',i.conversation,'reply_expected',r.reply_expected,'final',r.final)::text) AS payload
 FROM message_records m JOIN message_routes r ON r.message=m.id
 JOIN message_instances i ON i.id=r.recipient
 JOIN message_agent_inboxes a ON a.account=i.account AND a.project=i.project AND a.agent=i.agent;
INSERT INTO relay_payloads(digest,payload,byte_length,ejection_at)
 SELECT encode(sha256(convert_to(payload::text,'UTF8')),'hex'),payload,
  octet_length(convert_to(payload::text,'UTF8')),clock_timestamp()+interval '1 hour'
 FROM message_cutover_publications ON CONFLICT(digest) DO NOTHING;
INSERT INTO relay_publications(scope_key,topic,position,event_id,publisher,occurred_at,published_at,
 correlation_id,causation_id,schema_version,payload_digest)
 SELECT scope_key,topic,position,event_id,publisher,posted_at,clock_timestamp(),NULL,NULL,1,
  encode(sha256(convert_to(payload::text,'UTF8')),'hex') FROM message_cutover_publications;
UPDATE relay_topics t SET last_position=p.last_position FROM (
 SELECT scope_key,topic,max(position) AS last_position FROM message_cutover_publications GROUP BY scope_key,topic
) p WHERE t.scope_key=p.scope_key AND t.name=p.topic;
UPDATE message_routes SET published=true;

