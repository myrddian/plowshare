CREATE TABLE message_records (
 id TEXT PRIMARY KEY CHECK(id ~ '^bdm_[A-Za-z0-9]+$'),
 recipient TEXT NOT NULL REFERENCES message_instances(id),
 body TEXT NOT NULL CHECK(length(body)>0),
 posted_at TIMESTAMPTZ NOT NULL,
 seq BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);
INSERT INTO message_records(id,recipient,body,posted_at,seq)
 SELECT b.id,r.recipient,b.body,b.posted_at,b.seq FROM board_messages b
 JOIN message_routes r ON r.message=b.id ORDER BY b.seq;
SELECT setval(pg_get_serial_sequence('message_records','seq'),
 coalesce((SELECT max(seq) FROM message_records),1),EXISTS(SELECT 1 FROM message_records));
